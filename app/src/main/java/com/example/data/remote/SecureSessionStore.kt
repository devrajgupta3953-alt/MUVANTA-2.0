package com.example.data.remote

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec
import org.json.JSONObject

/**
 * Stores Supabase authentication sessions encrypted at rest using an Android Keystore
 * AES-256-GCM key (`AndroidKeyStore`).
 *
 * Security guarantees:
 * - Never writes plaintext access or refresh tokens to disk.
 * - Uses a fresh random 12-byte GCM IV on every write (generated by Android Keystore).
 * - Automatically migrates and permanently erases any legacy plaintext keys if present.
 * - Fails closed: corrupted or tampered ciphertext clears the stored session rather than
 *   falling back to plaintext.
 */
internal class SecureSessionStore(context: Context) {

    private val prefs = context.applicationContext.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)

    fun save(session: SupabaseSession) {
        val payload = JSONObject().apply {
            put(FIELD_UID, session.userId)
            put(FIELD_EMAIL, session.email)
            put(FIELD_ACCESS, session.accessToken)
            put(FIELD_REFRESH, session.refreshToken)
            put(FIELD_EXPIRES, session.expiresAtSeconds)
        }.toString()

        val encrypted = encrypt(payload)
        prefs.edit()
            .clear()
            .putString(KEY_ENCRYPTED_BLOB, encrypted)
            .apply()
    }

    fun load(): SupabaseSession? {
        val blob = prefs.getString(KEY_ENCRYPTED_BLOB, null)
        if (!blob.isNullOrBlank()) {
            val decrypted = runCatching { decrypt(blob) }.getOrNull()
            if (decrypted == null) {
                // Fail closed if ciphertext is tampered or keystore key was invalidated
                clear()
                return null
            }
            return parseSessionJson(decrypted)
        }

        // One-time transparent migration from legacy plaintext keys, immediately erasing them
        val legacyUid = prefs.getString(LEGACY_KEY_UID, null)
        val legacyAccess = prefs.getString(LEGACY_KEY_ACCESS, null)
        if (!legacyUid.isNullOrBlank() && !legacyAccess.isNullOrBlank()) {
            val migrated = SupabaseSession(
                userId = legacyUid,
                email = prefs.getString(LEGACY_KEY_EMAIL, "").orEmpty(),
                accessToken = legacyAccess,
                refreshToken = prefs.getString(LEGACY_KEY_REFRESH, "").orEmpty(),
                expiresAtSeconds = prefs.getLong(LEGACY_KEY_EXPIRES, 0L),
            )
            runCatching { save(migrated) }.onFailure { clear() }
            return migrated
        }
        return null
    }

    fun clear() {
        prefs.edit().clear().apply()
    }

    private fun parseSessionJson(raw: String): SupabaseSession? {
        val obj = runCatching { JSONObject(raw) }.getOrNull() ?: return null
        val uid = obj.optString(FIELD_UID, "").trim()
        val access = obj.optString(FIELD_ACCESS, "").trim()
        if (uid.isBlank() || access.isBlank()) return null
        return SupabaseSession(
            userId = uid,
            email = obj.optString(FIELD_EMAIL, "").trim(),
            accessToken = access,
            refreshToken = obj.optString(FIELD_REFRESH, "").trim(),
            expiresAtSeconds = obj.optLong(FIELD_EXPIRES, 0L),
        )
    }

    private fun getOrCreateSecretKey(): SecretKey {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        (keyStore.getKey(KEY_ALIAS, null) as? SecretKey)?.let { return it }

        val keyGenerator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        val spec = KeyGenParameterSpec.Builder(
            KEY_ALIAS,
            KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
        )
            .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
            .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
            .setKeySize(256)
            .setRandomizedEncryptionRequired(true)
            .build()
        keyGenerator.init(spec)
        return keyGenerator.generateKey()
    }

    private fun encrypt(plaintext: String): String {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateSecretKey())
        val iv = cipher.iv
        val ciphertext = cipher.doFinal(plaintext.toByteArray(Charsets.UTF_8))
        val ivB64 = Base64.encodeToString(iv, Base64.NO_WRAP)
        val ctB64 = Base64.encodeToString(ciphertext, Base64.NO_WRAP)
        return "$BLOB_VERSION:$ivB64:$ctB64"
    }

    private fun decrypt(encoded: String): String {
        val parts = encoded.split(":")
        require(parts.size == 3 && parts[0] == BLOB_VERSION) { "Unsupported encrypted session format" }
        val iv = Base64.decode(parts[1], Base64.NO_WRAP)
        val ciphertext = Base64.decode(parts[2], Base64.NO_WRAP)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateSecretKey(), GCMParameterSpec(GCM_TAG_BITS, iv))
        val plainBytes = cipher.doFinal(ciphertext)
        return String(plainBytes, Charsets.UTF_8)
    }

    companion object {
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val KEY_ALIAS = "muvanta_session_aes_gcm_v1"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
        private const val GCM_TAG_BITS = 128
        private const val BLOB_VERSION = "v1"

        private const val PREFS_NAME = "muvanta_supabase_session"
        private const val KEY_ENCRYPTED_BLOB = "enc_session_v1"

        private const val FIELD_UID = "uid"
        private const val FIELD_EMAIL = "email"
        private const val FIELD_ACCESS = "access"
        private const val FIELD_REFRESH = "refresh"
        private const val FIELD_EXPIRES = "expires"

        private const val LEGACY_KEY_UID = "uid"
        private const val LEGACY_KEY_EMAIL = "email"
        private const val LEGACY_KEY_ACCESS = "access"
        private const val LEGACY_KEY_REFRESH = "refresh"
        private const val LEGACY_KEY_EXPIRES = "expires"
    }
}
